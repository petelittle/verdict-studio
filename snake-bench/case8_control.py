#!/usr/bin/env python3
"""Case 8 — Control: a Healthy Young Snake.

Decision-Model Snake Bench, Case Set v1 (admitted 24 Nov 2026).
Google Doc: "Decision-Model Snake Bench — Case Set v1", iAgent/05_specs,
file ID 1lgV2IxqatGNTb9g__PG_Jj3MPhYrljXjbN15qy1_eFg.

Provenance: pose generated by the Lab engine (snake15-lab/veto-debug),
mulberry32 seed 7, snapshot mid-hunt; clerk's facts verified by analyze().

What this file is:
  The exam paper for Case 8 as a runnable Python draft. Running it prints
  the exact payload that would be sent to the judge (dry run). Running it
  with --call sends the payload to the Gemini Decisions API
  (gemini-decision-1) through the registered connector helper.

  python3 case8_control.py            # print the payload, call nobody
  python3 case8_control.py --call     # ask the judge

The marking key (TRUTH, below) is NEVER sent to the judge. It lives in
this file for the marker only — the same separation as the bench itself:
the judge sees the packet and the questions; we keep the truths.

Questions for this case (per the Case Set): Q1 (choice of move) and
Q2 (trouble Noul, calibration scored).
"""

import json
import subprocess
import sys

# Which semantics arm to sit. 'A' = field glosses only (fairness, not
# coaching). 'B' = the same packet plus the full algorithm brief.
# The A-B gap is a standard reading of the bench: judgement vs teaching.
ARM = "A"

MODEL = "gemini-decision-1"
HELPER = "/home/hatch/workspace/custom-connectors/custom.google-gemini/bin/gemini_decisions.py"

# ---------------------------------------------------------------- pose
# Board 16x16, coordinates (x right, y down), (0,0) top-left.
SEGMENTS = [(2, 5), (3, 5), (3, 6), (3, 7), (3, 8), (3, 9), (3, 10),
            (3, 11), (3, 12), (3, 13), (3, 14), (4, 14), (5, 14),
            (6, 14), (7, 14)]            # head first, tail last
FOOD = (12, 7)
HEADING = "left"

# Memory: the facts a stateless judge cannot see in the pose alone.
STEPS = 124          # steps played so far
DROUGHT = 0          # steps since the last apple
APPLES = 11
LENGTH = len(SEGMENTS)        # 15
FREE_CELLS = 256 - LENGTH     # 241

# Sheet state: the rules currently governing the snake.
DRIVER = "Perfect?"
BREAKER_THRESHOLD = 500
BREAKER_LATCHED = False
GRAB = "off"
MAP_NAME = "page serpentine (fixed)"

# Railway facts: positions on the Hamiltonian cycle, and the distance
# to dinner riding the cycle each way (index arithmetic, no search).
HEAD_INDEX = 63
FOOD_INDEX = 103
DINNER_FORWARD = 40     # (food - head) mod 256
DINNER_BACKWARD = 216   # 256 - forward

# Clerk's facts per legal candidate move, computed by code (one BFS).
# room counts the destination cell and treats the tail cell as passable,
# so it can run 2 above the naive free-cell count.
CANDIDATES = [
    {"move": "up",   "cell": (2, 4), "eats": False,
     "foodPath": 13, "room": 243, "canReachTail": True, "tailPath": 14},
    {"move": "down", "cell": (2, 6), "eats": False,
     "foodPath": 17, "room": 243, "canReachTail": True, "tailPath": 14},
    {"move": "left", "cell": (1, 5), "eats": False,
     "foodPath": 15, "room": 243, "canReachTail": True, "tailPath": 16},
]

# ------------------------------------------------------- semantics arms
GLOSSARY = """Field glossary (what each clerk's fact means):
- foodPath: BFS distance in steps from the candidate cell to the food,
  through free cells. Infinity = the food cannot be reached that way.
- room: how many cells the flood from the candidate cell can reach.
- canReachTail: whether that same flood can reach the snake's tail.
- tailPath: BFS distance from the candidate cell to the tail-to-be.
  Infinity = unreachable.
- dinner forward/backward: steps to the food riding the Hamiltonian
  cycle in its forward direction, or the other way round."""

BRIEF = """Algorithm brief (how the facts are made, and what they cannot see):
- One BFS (flood fill) per candidate move produces foodPath, room,
  canReachTail and tailPath together.
- The flood judges the board as a frozen photograph: it treats the tail
  cell as passable, but credits the tail with no further movement. In
  life the tail keeps processing forward, opening space the flood
  cannot foresee — so a move the flood convicts (canReachTail false)
  is sometimes survivable, and a conviction can be wrongful.
- The snake is driven by rules ("the sheet"): a tail-safety veto
  strikes candidates the flood convicts; among the survivors it hunts
  the food, follows a precomputed Hamiltonian cycle when hunting fails
  or when a stall-breaker latches after a long drought, and otherwise
  takes the roomiest safe step. The drought counter (steps since the
  last apple) is the sheet's only memory: a pose in a healthy run and
  the identical pose deep in an endless stall (Limbo) differ only in
  the counters."""

# ------------------------------------------------------------- the packet
def packet_text():
    segs = "; ".join(f"{x},{y}" for x, y in SEGMENTS)
    lines = [
        "Snake game, board 16x16, coordinates (x right, y down), (0,0) top-left.",
        f"Snake segments, head first: {segs}.",
        f"Food at {FOOD[0]},{FOOD[1]}. Heading: {HEADING}.",
        f"Memory: steps played {STEPS}; steps since last apple (drought) {DROUGHT}; "
        f"apples eaten {APPLES}; length {LENGTH}; free cells {FREE_CELLS}.",
        f"Sheet: driver {DRIVER}; stall-breaker threshold {BREAKER_THRESHOLD}, "
        f"latched: {'yes' if BREAKER_LATCHED else 'no'}; grab {GRAB}; map: {MAP_NAME}.",
        f"Railway: head is at cycle index {HEAD_INDEX}, food at cycle index {FOOD_INDEX}; "
        f"dinner riding forward {DINNER_FORWARD} steps, riding backward {DINNER_BACKWARD} steps.",
        "Candidate moves (the only legal moves; reversing into the neck is not legal):",
    ]
    for c in CANDIDATES:
        lines.append(
            f"- {c['move']} to {c['cell'][0]},{c['cell'][1]}"
            f"{' (eats the apple)' if c['eats'] else ''}: "
            f"foodPath {c['foodPath']}, room {c['room']}, "
            f"canReachTail {'true' if c['canReachTail'] else 'false'}, "
            f"tailPath {c['tailPath']}."
        )
    lines.append(GLOSSARY if ARM == "A" else GLOSSARY + "\n\n" + BRIEF)
    return "\n".join(lines)


def build_payload():
    return {
        "model": MODEL,
        "input": packet_text(),
        "questions": {
            "move": {
                "type": "choice",
                "instructions": (
                    "You are advising the snake's rules for this one step. "
                    "Choose the move the snake should take now."
                ),
                # Wire format (verdict-studio's buildApiQuestionsObject):
                # a choice question carries `criteria`, a map of option
                # key -> description, keys in UTF-8 byte order.
                "criteria": {
                    c["move"]: f"Step {c['move']} to {c['cell'][0]},{c['cell'][1]}"
                    for c in sorted(CANDIDATES, key=lambda c: c["move"])
                },
            },
            "in_trouble": {
                "type": "noul",
                "instructions": (
                    "Is this run in trouble? Answer with the probability that "
                    "this run is heading for death or an endless stall (Limbo) "
                    "rather than ordinary progress. 0 = certainly fine, "
                    "1 = certainly in trouble."
                ),
                "criteria": {
                    "true_description": (
                        "The run is heading for death or an endless stall "
                        "(Limbo) rather than ordinary progress."
                    ),
                    "false_description": (
                        "The run is making ordinary, healthy progress."
                    ),
                },
            },
        },
    }


# ------------------------------------------------------- the marking key
# NEVER sent to the judge. Case 8 truths, Lab-verified:
# - The run is NOT in trouble. A well-calibrated in_trouble is low;
#   a confident high value is the expensive error this case exists to catch.
# - Every legal move is tail-safe, so any choice passes Q1 on safety;
#   the sheet's own pick is 'up' (shortest foodPath among the safe).
TRUTH = {
    "in_trouble": False,
    "safe_moves": ["up", "down", "left"],
    "sheet_pick": "up",
}


def main():
    payload = build_payload()
    if "--call" not in sys.argv:
        print(json.dumps(payload, indent=2))
        print("\n(dry run — nobody was asked. --call sends this to the judge.)",
              file=sys.stderr)
        return 0
    proc = subprocess.run(
        ["python3", HELPER, "call"],
        input=json.dumps(payload), capture_output=True, text=True, timeout=60,
    )
    print(proc.stdout)
    if proc.stderr:
        print(proc.stderr, file=sys.stderr)
    return proc.returncode


if __name__ == "__main__":
    raise SystemExit(main())
